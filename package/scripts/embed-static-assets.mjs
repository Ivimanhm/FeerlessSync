import fs from 'node:fs';
import path from 'node:path';

const dist = path.resolve('dist');
const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
const assetPaths = [...html.matchAll(/"([^\"]*\/assets\/[^\"]+)"/g)]
  .map((match) => new URL(match[1], 'https://site.invalid').pathname);
const mimeTypes = {
  '.css': 'text/css; charset=utf-8',
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.jpg': 'image/jpeg',
  '.png': 'image/png',
};
const files = new Map([['/', path.join(dist, 'index.html')]]);
for (const assetPath of assetPaths) {
  const filename = path.resolve(dist, `.${assetPath}`);
  if (!filename.startsWith(`${dist}${path.sep}`) || !fs.statSync(filename).isFile()) {
    throw new Error(`Invalid or missing built asset: ${assetPath}`);
  }
  files.set(assetPath, filename);
}
for (const role of ['top', 'jungle', 'mid', 'adc', 'support']) {
  files.set(`/icons/roles/${role}.svg`, path.join(dist, 'icons', 'roles', `${role}.svg`));
}
files.set('/Logo-small.png', path.join(dist, 'Logo-small.png'));
files.set('/landscape.jpg', path.join(dist, 'landscape.jpg'));
for (const filename of fs.readdirSync(path.join(dist, 'champions')).filter((name) => name.endsWith('.jpg'))) {
  files.set(`/champions/${filename}`, path.join(dist, 'champions', filename));
}

const entries = [...files].map(([url, filename]) => {
  const content = fs.readFileSync(filename);
  const type = mimeTypes[path.extname(filename)] ?? 'application/octet-stream';
  return `  ${JSON.stringify(url)}: { type: ${JSON.stringify(type)}, data: ${JSON.stringify(content.toString('base64'))} },`;
});
const output = `// Generated by package/scripts/embed-static-assets.mjs during release builds.\nexport const staticAssets: Record<string, { type: string; data: string }> = {\n${entries.join('\n')}\n};\n`;
fs.writeFileSync(path.resolve('src/server/staticAssets.generated.ts'), output);
